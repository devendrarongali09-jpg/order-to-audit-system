# Transaction and audit records must not be deleted through ordinary
# model permissions, including by the Owner group.
NO_DELETE_MODELS = {
    "inventory.StockMovement",
    "inventory.Purchase",
    "inventory.PurchaseItem",

    "production.ProductionRun",
    "production.ProductionConsumption",
    "production.ProductionCost",

    "sales.SalesOrder",
    "sales.SalesOrderItem",
    "sales.InvoiceSequence",
    "sales.Invoice",
    "sales.InvoiceLine",
    "sales.Payment",
    "sales.Dispatch",
    "sales.DispatchItem",
}


# Records generated by controlled business workflows remain protected.
OWNER_READ_ONLY_MODELS = {
    "inventory.StockMovement",
    "production.ProductionConsumption",
    "sales.InvoiceSequence",
    "sales.Invoice",
    "sales.InvoiceLine",
}

OWNER_ADD_ONLY_MODELS = {
    "sales.Payment",
}


def build_owner_permissions():
    rules = {}

    for model_label in ALL_MODELS:
        if model_label in OWNER_READ_ONLY_MODELS:
            rules[model_label] = ("view",)

        elif model_label in OWNER_ADD_ONLY_MODELS:
            rules[model_label] = ("add", "view")

        elif model_label in NO_DELETE_MODELS:
            rules[model_label] = ("add", "view", "change")

        else:
            rules[model_label] = (
                "add", "view", "change", "delete"
            )

    return rules


ROLE_RULES["Owner"] = build_owner_permissions()


class Command(BaseCommand):
    help = "Create or update the project's five business role permissions."

    def get_permissions(self, model_label, actions):
        try:
            model = apps.get_model(model_label)
        except (LookupError, ValueError) as exc:
            raise CommandError(
                f"Unknown business model: {model_label}"
            ) from exc

        content_type = ContentType.objects.get_for_model(model)

        codenames = {
            f"{action}_{model._meta.model_name}"
            for action in actions
        }

        permissions = Permission.objects.filter(
            content_type=content_type,
            codename__in=codenames,
        )

        found = set(permissions.values_list("codename", flat=True))
        missing = codenames - found

        if missing:
            raise CommandError(
                f"Missing permissions for {model_label}: "
                f"{', '.join(sorted(missing))}. "
                "Check that migrations have been applied."
            )

        return list(permissions)

    @transaction.atomic
    def handle(self, *args, **options):
        self.stdout.write("Configuring business roles...")

        for role_name, model_rules in ROLE_RULES.items():
            group, created = Group.objects.get_or_create(
                name=role_name
            )

            permissions = []

            for model_label, actions in model_rules.items():
                permissions.extend(
                    self.get_permissions(model_label, actions)
                )

            # Replace permissions with the defined role policy.
            group.permissions.set(permissions)

            status = "Created" if created else "Updated"

            self.stdout.write(
                self.style.SUCCESS(
                    f"{status}: {role_name} | "
                    f"{len(permissions)} permissions"
                )
            )

        self.stdout.write(
            self.style.SUCCESS(
                "All five business roles configured successfully."
            )
        )

        self.stdout.write(
            self.style.WARNING(
                "User assignments and row-level restrictions "
                "have not been configured by this command."
            )
        )
